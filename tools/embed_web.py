#!/usr/bin/env python3
"""The browser UI's files (web/, plus the app's bundled fonts and their licences) as a C header the addin compiles in:
each file gzipped (reproducibly: no name, no time), with its content type and an ETag from its hash.
Usage: tools/embed_web.py <out.h>. Run by build.sh, build-aarch64.sh and tests/test.sh."""
import gzip, hashlib, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "app", "crates", "commander", "assets", "fonts")
TYPES = {".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
         ".ttf": "font/ttf", ".txt": "text/plain; charset=utf-8", ".svg": "image/svg+xml"}

# served path (after /web/, index.html also at /) -> source file
files = {}
for name in sorted(os.listdir(os.path.join(ROOT, "web"))):
    if os.path.splitext(name)[1] in TYPES:
        files[name] = os.path.join(ROOT, "web", name)
for name in ("TitilliumWeb-Regular.ttf", "TitilliumWeb-SemiBold.ttf", "TitilliumWeb-Bold.ttf", "Roboto-Bold.ttf",
             "NOTICE.txt", "OFL.txt", "Roboto-LICENSE.txt"):
    files["fonts/" + name] = os.path.join(FONTS, name)
if "index.html" not in files:
    sys.exit("web/index.html is missing")

out = ["// Generated by tools/embed_web.py from web/ and the app's fonts: do not edit.",
       "#include <stddef.h>",
       "struct web_asset { const char *path, *type, *etag; const unsigned char *data; size_t len; };"]
table = []
for k, (path, src) in enumerate(files.items()):
    raw = open(src, "rb").read()
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    etag = '"%s"' % hashlib.sha256(raw).hexdigest()[:16]
    body = ",".join(str(b) for b in gz)
    out.append("static const unsigned char web_asset_%d[%d] = {%s};" % (k, len(gz), body))
    table.append('    { "%s", "%s", "\\"%s\\"", web_asset_%d, %d },'
                 % (path, TYPES[os.path.splitext(path)[1]], etag.strip('"'), k, len(gz)))
out.append("static const struct web_asset web_assets[] = {")
out += table
out.append("};")
out.append("#define WEB_ASSETS (sizeof web_assets / sizeof web_assets[0])")
os.makedirs(os.path.dirname(os.path.abspath(sys.argv[1])), exist_ok=True)
tmp = sys.argv[1] + ".tmp"
with open(tmp, "w") as f:
    f.write("\n".join(out) + "\n")
os.replace(tmp, sys.argv[1])
total = sum(len(gzip.compress(open(s, "rb").read(), 9, mtime=0)) for s in files.values())
print("embed_web: %d files, %d KB gzipped -> %s" % (len(files), total // 1024, sys.argv[1]))
